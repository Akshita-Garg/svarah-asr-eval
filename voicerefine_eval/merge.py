"""Merge independent evaluation runs without invoking any ASR backend.

Each source run remains immutable. The merger validates that every source used
the same frozen Svarah subset, rejects duplicate backend/utterance rows, then
recomputes the comparison report from the stored per-utterance records.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import sys
from pathlib import Path
from typing import Any

from .config import REPO_ROOT
from .hashing import sha256_file, write_json_atomic
from .report import (
    read_per_utterance_csv,
    shared_success_metrics,
    summarize_backend,
    write_per_utterance_csv,
    write_summary_md,
)
from .results import UtteranceResult


def _resolve(path: str) -> Path:
    candidate = Path(path)
    return candidate.resolve() if candidate.is_absolute() else (REPO_ROOT / candidate).resolve()


def _portable_path(path: Path) -> str:
    """Prefer a repository-relative path in committed comparison metadata."""
    try:
        return path.resolve().relative_to(REPO_ROOT).as_posix()
    except ValueError:
        return str(path.resolve())


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Merge VoiceRefine evaluation runs")
    parser.add_argument("--inputs", required=True, help="Comma-separated run directories")
    parser.add_argument("--output-dir", required=True, help="Directory for combined artifacts")
    parser.add_argument(
        "--backends",
        default=None,
        help="Optional comma-separated backend ids to retain from the source runs",
    )
    return parser.parse_args(argv)


def _load_run(run_dir: Path) -> tuple[dict[str, Any], list[UtteranceResult]]:
    manifest_path = run_dir / "run_manifest.json"
    csv_path = run_dir / "per_utterance.csv"
    if not manifest_path.exists() or not csv_path.exists():
        raise ValueError(f"Run directory is missing required artifacts: {run_dir}")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    return manifest, read_per_utterance_csv(csv_path)


def _dataset_identity(manifest: dict[str, Any]) -> dict[str, Any]:
    dataset = manifest.get("dataset", {})
    keys = ("name", "revision", "split", "seed", "subset_size", "debug")
    return {key: dataset.get(key) for key in keys}


def _startup_times(run_dir: Path, manifest: dict[str, Any]) -> dict[str, float | None]:
    structured = manifest.get("backend_summaries", {})
    times = {
        backend_id: details.get("startup_seconds")
        for backend_id, details in structured.items()
    }
    if times:
        return times

    # Compatibility for the original baseline, created before startup timing
    # was included in the JSON manifest. Its Markdown table is generated by us.
    summary_path = run_dir / "summary.md"
    if not summary_path.exists():
        return {}
    for line in summary_path.read_text(encoding="utf-8").splitlines():
        if not line.startswith("|") or line.startswith("| ---"):
            continue
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if len(cells) == 12 and cells[0] not in ("Backend", ""):
            try:
                times[cells[0]] = float(cells[-1]) if cells[-1] else None
            except ValueError:
                continue
    return times


def merge_runs(
    input_dirs: list[Path],
    output_dir: Path,
    *,
    backend_ids: set[str] | None = None,
) -> dict[str, Any]:
    if len(input_dirs) < 2:
        raise ValueError("At least two run directories are required for a comparison")

    loaded = [(run_dir, *_load_run(run_dir)) for run_dir in input_dirs]
    expected_dataset = _dataset_identity(loaded[0][1])
    expected_eval_ids: set[str] | None = None
    references: dict[str, str] = {}
    seen_keys: set[tuple[str, str]] = set()
    results_by_backend: dict[str, list[UtteranceResult]] = {}
    backend_signatures: dict[str, Any] = {}
    startup_times: dict[str, float | None] = {}

    for run_dir, manifest, results in loaded:
        identity = _dataset_identity(manifest)
        if identity != expected_dataset:
            raise ValueError(
                f"Dataset mismatch in {run_dir}: expected {expected_dataset}, got {identity}"
            )

        if backend_ids is not None:
            results = [result for result in results if result.backend_id in backend_ids]
        run_backend_ids = list(dict.fromkeys(result.backend_id for result in results))
        if not run_backend_ids:
            continue
        for backend_id in run_backend_ids:
            rows = [result for result in results if result.backend_id == backend_id]
            ids = {result.eval_id for result in rows}
            if len(rows) != expected_dataset["subset_size"] or len(ids) != len(rows):
                raise ValueError(
                    f"Backend {backend_id} in {run_dir} does not contain exactly "
                    f"{expected_dataset['subset_size']} unique utterances"
                )
            if expected_eval_ids is None:
                expected_eval_ids = ids
            elif ids != expected_eval_ids:
                raise ValueError(f"Utterance set mismatch for {backend_id} in {run_dir}")

            for result in rows:
                key = (result.backend_id, result.eval_id)
                if key in seen_keys:
                    raise ValueError(f"Duplicate result row: {key}")
                seen_keys.add(key)
                previous_reference = references.setdefault(result.eval_id, result.raw_reference)
                if previous_reference != result.raw_reference:
                    raise ValueError(f"Reference mismatch for {result.eval_id} in {run_dir}")
            results_by_backend[backend_id] = rows

        for backend_id, signature in manifest.get("backends", {}).items():
            if backend_ids is not None and backend_id not in backend_ids:
                continue
            if backend_id in backend_signatures:
                raise ValueError(f"Duplicate backend provenance: {backend_id}")
            backend_signatures[backend_id] = signature
        run_startup_times = _startup_times(run_dir, manifest)
        startup_times.update(
            {
                backend_id: seconds
                for backend_id, seconds in run_startup_times.items()
                if backend_ids is None or backend_id in backend_ids
            }
        )

    if backend_ids is not None:
        missing = backend_ids - set(results_by_backend)
        if missing:
            raise ValueError(f"Requested backends were not found: {sorted(missing)}")

    all_results = [result for rows in results_by_backend.values() for result in rows]
    summaries = {
        backend_id: summarize_backend(
            backend_id,
            rows,
            available=True,
            startup_seconds=startup_times.get(backend_id),
            total_attempted=expected_dataset["subset_size"],
        )
        for backend_id, rows in results_by_backend.items()
    }
    shared_ids, shared_metrics = shared_success_metrics(results_by_backend)

    output_dir.mkdir(parents=True, exist_ok=True)
    write_per_utterance_csv(all_results, output_dir / "per_utterance.csv")
    write_summary_md(
        summaries=summaries,
        shared_ids=shared_ids,
        shared_metrics=shared_metrics,
        dataset_name=expected_dataset["name"],
        revision=expected_dataset["revision"],
        split=expected_dataset["split"],
        seed=expected_dataset["seed"],
        subset_size=expected_dataset["subset_size"],
        debug=expected_dataset["debug"],
        path=output_dir / "summary.md",
    )

    comparison_manifest = {
        "type": "combined_comparison",
        "created_at": dt.datetime.now(dt.timezone.utc).isoformat(),
        "dataset": expected_dataset,
        "source_runs": [
            {
                "path": _portable_path(run_dir),
                "run_manifest_sha256": sha256_file(run_dir / "run_manifest.json"),
                "per_utterance_sha256": sha256_file(run_dir / "per_utterance.csv"),
            }
            for run_dir, _, _ in loaded
        ],
        "selected_backends": sorted(backend_ids) if backend_ids is not None else None,
        "backends": backend_signatures,
        "backend_count": len(results_by_backend),
        "row_count": len(all_results),
        "shared_successful_utterances": len(shared_ids),
    }
    write_json_atomic(output_dir / "comparison_manifest.json", comparison_manifest)
    return comparison_manifest


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    input_dirs = [_resolve(value.strip()) for value in args.inputs.split(",") if value.strip()]
    output_dir = _resolve(args.output_dir)
    backend_ids = (
        {value.strip() for value in args.backends.split(",") if value.strip()}
        if args.backends
        else None
    )
    manifest = merge_runs(input_dirs, output_dir, backend_ids=backend_ids)
    print(
        f"Merged {manifest['backend_count']} backends and {manifest['row_count']} rows "
        f"into {output_dir}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
